// ABOUTME: Aggregate 2026-05-29 reports into one summary doc. Pulls win-rate tables from each report markdown.
// ABOUTME: Run after sweeps complete to produce a one-page overview for Sam.

import { writeFileSync, readFileSync, readdirSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const REPORTS_DIR = resolve(process.cwd(), "docs");
const OUT_PATH = resolve(process.cwd(), "docs/2026-05-29-results-aggregate.md");

interface ReportRow {
  filename: string;
  title: string;
  summary: string;
}

function listReports(): string[] {
  return readdirSync(REPORTS_DIR)
    .filter((f: string) => f.startsWith("2026-05-29-") && f.endsWith(".md") && f !== "2026-05-29-results-aggregate.md")
    .sort();
}

function extractSummary(content: string): { title: string; summary: string } {
  const lines = content.split("\n");
  const title = lines[0]?.replace(/^# /, "").trim() ?? "untitled";
  // Find the first markdown table — the "## Results" section's main table.
  const summaryLines: string[] = [];
  let inTable = false;
  let tableLines = 0;
  for (const line of lines) {
    if (line.startsWith("|") && !inTable) {
      inTable = true;
      summaryLines.push(line);
      tableLines = 1;
    } else if (line.startsWith("|") && inTable) {
      summaryLines.push(line);
      tableLines += 1;
      if (tableLines >= 12) break; // cap the row count
    } else if (inTable && !line.startsWith("|") && tableLines > 1) {
      break;
    }
  }
  return { title, summary: summaryLines.join("\n") };
}

function main() {
  const reports = listReports();
  const rows: ReportRow[] = [];
  for (const filename of reports) {
    const path = resolve(REPORTS_DIR, filename);
    if (!existsSync(path)) continue;
    const content = readFileSync(path, "utf8");
    const { title, summary } = extractSummary(content);
    rows.push({ filename, title, summary });
  }

  const out: string[] = [];
  out.push(`# 2026-05-29 Results — Aggregate Summary`);
  out.push(``);
  out.push(`Auto-generated by \`src/sweep/2026-05-29-aggregate-results.ts\`. Pulls the first results table from each \`2026-05-29-*.md\` report. Run after sweeps complete to refresh.`);
  out.push(``);
  out.push(`**${rows.length} reports** included.`);
  out.push(``);
  for (const r of rows) {
    out.push(`## ${r.title}`);
    out.push(``);
    out.push(`Source: [\`${r.filename}\`](./${r.filename})`);
    out.push(``);
    if (r.summary.length > 0) {
      out.push(r.summary);
    } else {
      out.push(`*(no table found)*`);
    }
    out.push(``);
    out.push(`---`);
    out.push(``);
  }
  writeFileSync(OUT_PATH, out.join("\n") + "\n", "utf8");
  console.log(`Wrote ${OUT_PATH} (${rows.length} reports)`);
}

main();
